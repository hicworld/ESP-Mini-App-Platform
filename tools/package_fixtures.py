"""Sign device-only fault injection fixtures with the local development identity."""
import json
from pathlib import Path
from cryptography.hazmat.primitives import serialization
from app_package import create
root=Path(__file__).resolve().parents[1]
key=serialization.load_pem_private_key((root/'local/dev_private.pem').read_bytes(),password=None)
cases=json.loads((root/'dist/fixtures/cases.json').read_text())
lines=['/* Generated by tools/package_fixtures.py. Development test fixtures. */']
for i,case in enumerate(cases):
    permissions=[] if case['name'] in ('no_permission','storage_no_permission') else (['storage'] if case['name'].startswith('storage') else ['display'])
    if case['name'].startswith('audio'): permissions=[] if case['name']=='audio_no_permission' else ['audio']
    fixture_id={
        'storage_write_limit':'com.test.storagewrite',
        'storage_key_limit':'com.test.storagekeys',
    }.get(case['name'],'com.test.fixture')
    m={'manifest_version':1,'api_version':1,'id':fixture_id,'name':case['name'],'version':'0.1.0','platform_min':'0.1.0','entry':'main.wasm','permissions':permissions,'hardware':[]}
    if case['name']=='future_platform': m['platform_min']='65535.65535.65535'
    package=create(m,(root/f'dist/fixtures/{case["name"]}.wasm').read_bytes(),key)
    lines.append(f'static const uint8_t fixture_{i}[] = {{'+','.join(str(b) for b in package)+'};')
lines.append('static const fixture_t fixtures[] = {')
for i,c in enumerate(cases):
    lines.append('{"%s",fixture_%d,sizeof(fixture_%d),%s,%d},'%(c['name'],i,i,'true' if c['fail'] else 'false',c['event']))
lines.append('};')
(root/'firmware/main/fixtures.inc').write_text('\n'.join(lines)+'\n')
print('Generated signed on-device selftest fixtures')
